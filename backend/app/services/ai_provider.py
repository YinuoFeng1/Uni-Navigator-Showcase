import hashlib
import logging
from dataclasses import dataclass, field
from typing import Any

import httpx

from app.config import Settings, get_settings

logger = logging.getLogger(__name__)

REVISION_PROMPT_TEMPLATE = """
The previous draft failed the answer contract. Rewrite the complete answer
using the same evidence and do not add any new claim. Return only the corrected
answer. Every paragraph must contain exactly one sentence. Never output
standalone "Yes." or "No." text. The sentence identified by the validation
issue must either contain an allowed citation label or be removed.
""".strip()

SYSTEM_PROMPT = """
You are Uni-Navigator. Help students understand university administrative
policy information in concise, plain English.

Follow this answer contract:
- Start with a direct answer to the student's question. Do not begin with a
  disclaimer, retrieval summary, or phrases such as "Based on the evidence" or
  "I found".
- Use only the retrieved context for policy rules, deadlines, forms,
  eligibility, required evidence, and process steps. Never guess or add a rule.
- Do not infer that something is prohibited, excluded, automatic, or without
  effect merely because the retrieved excerpts do not mention it. Corpus
  silence is not policy evidence. Say "The retrieved official policy evidence
  does not establish whether ..." for any such unresolved point.
- Prefer the highest-ranked excerpt that directly addresses the requested rule
  or decision-maker. Do not substitute a broader related process for the
  specific process asked about.
- Put one or more provided citation labels immediately after every sentence
  that states a policy conclusion. Use only labels listed as allowed. Never
  invent, renumber, or cite a source that was not provided.
- Treat every sentence independently: a citation in a later sentence does not
  support an earlier sentence. Use one sentence per paragraph, and end each
  source-backed paragraph with its citation label or labels.
- A yes/no answer about eligibility, approval, visa status, or another personal
  outcome is a policy conclusion. Give that answer only when an excerpt states
  it directly. Otherwise state the supported general rule and the unresolved
  personal outcome separately. Never write a standalone "Yes." or "No." under
  any evidence status. Put the direct answer and its supporting citation in the
  same complete sentence.
- Before returning the answer, check every sentence ending in a full stop,
  question mark, or exclamation mark. Each policy sentence must contain an
  allowed citation label before its ending punctuation.
- Keep the answer under 140 words. Prefer two or three short paragraphs. Do not
  repeat the same limitation or staff-contact advice.
- Do not include a general research-prototype or "not official advice"
  disclaimer in the answer. The interface presents limitations separately.

Use the evidence status precisely:
- grounded: answer the supported question directly with citations.
- partial_evidence: answer only the supported part with citations, then state
  briefly: "The retrieved official policy evidence does not establish ..."
- individual_assessment: state the general policy rule with citations, then say
  "Your personal outcome needs confirmation by authorised university staff."
  Do not predict the student's outcome. For an unresolved yes/no question,
  begin with "The retrieved official policy evidence does not establish
  whether ..." instead of yes or no.
- ambiguous: separate the supported policy point from the unresolved part. Do
  not present the unresolved part as a policy conclusion.
- insufficient_evidence: start exactly with "There is not enough matching
  official policy evidence to answer this question." Do not use contractions,
  make policy claims, add citations, or invent a specific office. Then say:
  "Contact authorised university staff for help with the next step."
""".strip()

SAFE_LIMITATIONS = (
    "This response is generated by a research prototype and is not official "
    "university advice. No official policy evidence was available for this "
    "answer."
)

GROUNDED_LIMITATIONS = (
    "This response is generated by a research prototype and is not official "
    "university advice. It is limited to the retrieved policy excerpts shown in "
    "the citations and may not cover every rule, exception, deadline, or "
    "personal circumstance."
)

@dataclass(frozen=True)
class AIProviderResult:
    text: str
    provider_name: str
    model_name: str
    provider_mode: str
    retrieval_status: str = "insufficient_evidence"
    limitations: str = SAFE_LIMITATIONS
    provider_response_id: str | None = None
    token_usage: dict[str, Any] = field(default_factory=dict)


class AIProviderError(Exception):
    """Raised when a provider cannot produce a usable answer."""


class BaseAIProvider:
    provider_name = "unknown"

    def __init__(self, model_name: str, timeout_seconds: float) -> None:
        self.model_name = model_name
        self.timeout_seconds = timeout_seconds

    def generate_answer(
        self,
        question: str,
        retrieved_context: str | None = None,
        citation_labels: list[str] | None = None,
        retrieval_status: str = "insufficient_evidence",
        previous_answer: str | None = None,
        validation_feedback: str | None = None,
    ) -> AIProviderResult:
        raise NotImplementedError


def build_limitations(retrieval_status: str, has_context: bool) -> str:
    if has_context:
        return GROUNDED_LIMITATIONS

    return SAFE_LIMITATIONS


class OpenAIProvider(BaseAIProvider):
    provider_name = "openai"

    def __init__(
        self,
        model_name: str,
        timeout_seconds: float,
        api_key: str,
        prompt_template_version: str,
        generation_temperature: float,
        generation_max_tokens: int,
        generation_reasoning_effort: str,
    ) -> None:
        super().__init__(model_name=model_name, timeout_seconds=timeout_seconds)
        self.api_key = api_key
        self.prompt_template_version = prompt_template_version
        self.generation_temperature = generation_temperature
        self.generation_max_tokens = generation_max_tokens
        self.generation_reasoning_effort = generation_reasoning_effort

    def generate_answer(
        self,
        question: str,
        retrieved_context: str | None = None,
        citation_labels: list[str] | None = None,
        retrieval_status: str = "insufficient_evidence",
        previous_answer: str | None = None,
        validation_feedback: str | None = None,
    ) -> AIProviderResult:
        if not self.api_key:
            raise AIProviderError("OPENAI_API_KEY is not configured")

        try:
            has_context = bool(retrieved_context and citation_labels)
            with httpx.Client(timeout=self.timeout_seconds) as client:
                response = client.post(
                    "https://api.openai.com/v1/responses",
                    headers={
                        "Authorization": f"Bearer {self.api_key}",
                        "Content-Type": "application/json",
                    },
                    json={
                        "model": self.model_name,
                        "instructions": _system_prompt(self.prompt_template_version),
                        "input": _build_grounded_input(
                            question=question,
                            retrieved_context=retrieved_context,
                            citation_labels=citation_labels or [],
                            retrieval_status=retrieval_status,
                            previous_answer=previous_answer,
                            validation_feedback=validation_feedback,
                        ),
                        "temperature": self.generation_temperature,
                        "max_output_tokens": self.generation_max_tokens,
                        "reasoning": {
                            "effort": self.generation_reasoning_effort,
                        },
                    },
                )
            response.raise_for_status()
            payload = response.json()
            text = _extract_response_text(payload)
            response_model = _optional_text(payload.get("model")) or self.model_name
            return AIProviderResult(
                text=text,
                provider_name=self.provider_name,
                model_name=response_model,
                provider_mode="openai",
                retrieval_status=retrieval_status,
                limitations=build_limitations(retrieval_status, has_context),
                provider_response_id=_optional_text(payload.get("id")),
                token_usage=_extract_token_usage(payload),
            )
        except AIProviderError:
            raise
        except Exception as exc:
            logger.warning("OpenAI provider request failed: %s", type(exc).__name__)
            raise AIProviderError("OpenAI answer generation failed") from exc


def _extract_response_text(payload: dict[str, Any]) -> str:
    output_text = payload.get("output_text")
    if isinstance(output_text, str) and output_text.strip():
        return output_text.strip()

    output = payload.get("output")
    if isinstance(output, list):
        for item in output:
            if not isinstance(item, dict):
                continue
            content = item.get("content")
            if not isinstance(content, list):
                continue
            for content_item in content:
                if not isinstance(content_item, dict):
                    continue
                if content_item.get("type") != "output_text":
                    continue
                text = content_item.get("text")
                if isinstance(text, str) and text.strip():
                    return text.strip()

    raise AIProviderError("OpenAI response did not include output text")


def _extract_token_usage(payload: dict[str, Any]) -> dict[str, Any]:
    usage = payload.get("usage")
    if not isinstance(usage, dict):
        return {}
    return _numeric_usage_values(usage)


def _numeric_usage_values(value: dict[str, Any]) -> dict[str, Any]:
    output: dict[str, Any] = {}
    for key, item in value.items():
        if isinstance(item, bool):
            continue
        if isinstance(item, int | float):
            output[str(key)] = item
        elif isinstance(item, dict):
            nested = _numeric_usage_values(item)
            if nested:
                output[str(key)] = nested
    return output


def _optional_text(value: Any) -> str | None:
    return value.strip() if isinstance(value, str) and value.strip() else None


def _system_prompt(version: str) -> str:
    if version != "grounded-v9":
        raise AIProviderError(f"Unsupported prompt template version: {version}")
    return SYSTEM_PROMPT


def prompt_fingerprint(version: str) -> str:
    prompt = f"{_system_prompt(version)}\n\n{REVISION_PROMPT_TEMPLATE}"
    return f"sha256:{hashlib.sha256(prompt.encode('utf-8')).hexdigest()}"


def _build_grounded_input(
    question: str,
    retrieved_context: str | None,
    citation_labels: list[str],
    retrieval_status: str,
    previous_answer: str | None = None,
    validation_feedback: str | None = None,
) -> str:
    revision = _revision_request(previous_answer, validation_feedback)
    if retrieved_context:
        allowed_labels = ", ".join(citation_labels)
        return (
            f"Evidence status: {retrieval_status}\n"
            f"Allowed citation labels: {allowed_labels}\n\n"
            "Retrieved context. Use only these excerpts for policy-specific "
            "claims and cite them with their labels:\n\n"
            f"{retrieved_context}\n\n"
            f"Student question: {question}{revision}"
        )

    return (
        f"Evidence status: {retrieval_status}\n"
        "Allowed citation labels: none\n\n"
        "No retrieved policy context was available. Do not make policy-specific "
        "claims or cite sources.\n\n"
        f"Student question: {question}{revision}"
    )


def _revision_request(
    previous_answer: str | None,
    validation_feedback: str | None,
) -> str:
    if not previous_answer or not validation_feedback:
        return ""
    return (
        f"\n\n{REVISION_PROMPT_TEMPLATE}\n"
        f"Validation issue: {validation_feedback}\n"
        f"Previous draft:\n{previous_answer}"
    )


def get_ai_provider(settings: Settings | None = None) -> BaseAIProvider:
    settings = settings or get_settings()
    provider_name = settings.ai_provider

    if provider_name != "openai":
        raise AIProviderError("AI_PROVIDER must be openai")
    return OpenAIProvider(
        model_name=settings.ai_model,
        timeout_seconds=settings.ai_timeout_seconds,
        api_key=settings.openai_api_key,
        prompt_template_version=settings.prompt_template_version,
        generation_temperature=settings.generation_temperature,
        generation_max_tokens=settings.generation_max_tokens,
        generation_reasoning_effort=settings.generation_reasoning_effort,
    )
